"""Serves the Manager Charts dashboard (a Vue app) at /bb-reports and /bb-reports/<anything>.

bb-reports.html (next to this bb_reports.py -- Frappe maps "-" to "_") is generated by `frontend/scripts/make-page.mjs` during the frontend build
(`bench build --app bb_report_manager`). Signed-out visitors are sent to the standard login.
"""

from urllib.parse import quote

import frappe
from frappe import _

from bb_report_manager.install import REPORT_ROLE

no_cache = 1


def get_context(context):
	if frappe.session.user == "Guest":
		# Keep the query string so a shared, filtered report link survives the login.
		target = frappe.request.full_path.rstrip("?") if frappe.request else "/bb-reports"
		frappe.local.flags.redirect_location = "/login?redirect-to=" + quote(target, safe="")
		raise frappe.Redirect

	if not set(frappe.get_roles()).intersection({REPORT_ROLE, "System Manager", "Administrator"}):
		frappe.throw(
			_("You need the {0} role to view the manager charts").format(REPORT_ROLE), frappe.PermissionError
		)

	csrf_token = frappe.sessions.get_csrf_token()
	frappe.db.commit()  # get_csrf_token may have written the session
	context.csrf_token = csrf_token
	context.user_full_name = frappe.utils.get_fullname(frappe.session.user)
	context.no_cache = 1
	return context
